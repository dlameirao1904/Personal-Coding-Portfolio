export function plain(value: string) {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
}

export function albumById(id: string | null) {
  return ALBUMS.find((album) => album.id === id) ?? null
}
